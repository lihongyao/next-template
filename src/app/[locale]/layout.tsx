// src/app/[locale]/layout.tsx
import { Suspense } from 'react';

import type { Metadata, Viewport } from 'next';
import { hasLocale } from 'next-intl';
import { getMessages, setRequestLocale } from 'next-intl/server';
import { headers } from 'next/headers';
import { notFound } from 'next/navigation';

import '@/app/globals.css';
import '@/assets/styles/global-animate.css';
import SpriteSvgSource from '@/assets/svg/generated/sprite-svg';
import ClientSideScrollRestorer from '@/components/features/ClientSideScrollRestorer';
import { CURRENT_VERSION } from '@/constants';
import { inter } from '@/fonts';
import '@/generated/brand.css';
import { routing } from '@/i18n/routing';
import { getServerBrandConfig } from '@/libs/brand.server';
import { AppProviders } from '@/providers/app.provider';

export const runtime = 'edge';
export const viewport: Viewport = {
  width: 'device-width',
  initialScale: 1,
  minimumScale: 1,
  maximumScale: 1,
  userScalable: false,
  viewportFit: 'cover',
};

export const metadata: Metadata = {
  title: 'Create Next App',
  description: 'Generated by create next app',
};

export default async function LocaleLayout({
  children,
  params,
}: Readonly<{
  children: React.ReactNode;
  params: Promise<{ locale: string }>;
}>) {
  const { locale } = await params;

  // Ensure that the incoming `locale` is valid
  if (!hasLocale(routing.locales, locale)) {
    notFound();
  }

  // Enable static rendering
  setRequestLocale(locale);

  // Providing all messages to the client
  // side is the easiest way to get started
  const messages = await getMessages();

  // 获取品牌配置
  const brandConfig = await getServerBrandConfig();

  const userAgent = (await headers()).get('user-agent') || '';

  return (
    <html
      lang={locale}
      className="no-scrollbar"
      data-theme={brandConfig.theme}
      data-skin={brandConfig.skin}
      data-version={CURRENT_VERSION}
    >
      <head>
        {/* Theme color - 谷歌浏览器工具栏主题色（safari取页面颜色，一般是body） */}
        <meta name="theme-color" content={'#161616'} />
        {/* PWA - 隐藏地址栏、底部工具栏，解决 iOS 双击放大 */}
        {/* For iOS Safari*/}
        <meta name="apple-mobile-web-app-capable" content="yes" />
        {/* For Android Chrome */}
        <meta name="mobile-web-app-capable" content="yes" />
        {/* PWA - 添加 manifest.json */}
        <link rel="manifest" href="/manifest.json" />
      </head>

      <body className={inter.className} style={{ background: '#101010' }}>
        <SpriteSvgSource />
        {/* lcp element */}
        <img
          className="lcp-anchor"
          src={`/res/${process.env.NEXT_PUBLIC_BRAND}/logo.png`}
          alt="lcp"
          role="none"
        />
        <AppProviders
          locale={locale}
          messages={messages}
          brandConfig={brandConfig}
          userAgent={userAgent}
        >
          {children}
        </AppProviders>
        {/* 记录滚动位置 */}
        <Suspense>
          <ClientSideScrollRestorer />
        </Suspense>
      </body>
    </html>
  );
}
